import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { _electron as electron, expect, test, type ElectronApplication, type Page } from '@playwright/test'
import sharp from 'sharp'
import type { DadosLivro } from '../../src/shared/api'

function dados(titulo: string, status: DadosLivro['status'] = 'quero_ler'): DadosLivro {
  return { titulo, tituloOriginal: null, colaboradores: [{ nome: 'Autora', pais: null, papel: 'autor' }], isbn10: null, isbn13: null, editora: null, paisEditora: null, serie: null, volume: null, tipo: 'livro', formato: 'fisico', paginas: 200, paginasEstimadas: false, anoEdicao: null, anoPublicacao: null, idioma: null, sinopse: null, posse: null, status, generos: [], temas: [], moods: [], notasPrivadas: 'Nota preservada' }
}
test.describe('etapa 6: organização', () => {
  let raiz: string, pasta: string, app: ElectronApplication, janela: Page, erros: string[]
  test.beforeEach(async () => {
    raiz = mkdtempSync(join(tmpdir(), 'bela-etapa6-')); pasta = join(raiz, 'dados'); mkdirSync(pasta)
    const { ELECTRON_RENDERER_URL: _url, ELECTRON_RUN_AS_NODE: _node, ...ambiente } = process.env
    app = await electron.launch({ args: [resolve('.')], env: { ...ambiente, BELA_PASTA_DADOS: pasta, BELA_ARQUIVO_ENV: join(pasta, '.env') } as Record<string, string> })
    janela = await app.firstWindow(); erros = []
    janela.on('pageerror', (e) => erros.push(e.message))
    janela.on('console', (m) => { if (m.type() === 'error') erros.push(m.text()) })
    await janela.setViewportSize({ width: 1400, height: 900 })
    const lista = [dados('Aurora', 'lido'), dados('Brisa', 'lendo'), dados('Céu'), dados('Duna'), dados('Estrela')]
    lista[0].leituraInicial = { status: 'lido', formato: 'fisico', dataInicio: null, dataFim: `${new Date().getFullYear()}-01-15`, anoFim: new Date().getFullYear(), precisaoFim: 'dia', nota: 5, resenha: 'Resenha original' }
    const png = await sharp({ create: { width: 120, height: 180, channels: 3, background: '#7E2F3A' } }).png().toBuffer()
    await janela.evaluate(async ({ lista, imagem }) => { for (let i = 0; i < lista.length; i++) await window.bela.livros.salvar(lista[i], false, i === 0 ? { bytes: imagem } : undefined) }, { lista, imagem: Array.from(png) })
  })
  test.afterEach(async () => { try { expect(erros).toEqual([]) } finally { await app.close(); rmSync(raiz, { recursive: true, force: true, maxRetries: 3 }) } })

  test('personaliza perfil, escolhe e ordena quatro favoritos, registra progresso e organiza a fila', async () => {
    // Favoritos só podem ser livros lidos.
    const lidos = ['Folha', 'Gema', 'Hera', 'Íris'].map((t) => { const d = dados(t, 'lido'); d.leituraInicial = { status: 'lido', formato: 'fisico', dataInicio: null, dataFim: null, anoFim: 2024, precisaoFim: 'ano', nota: 4, resenha: null }; return d })
    await janela.evaluate(async (lista) => { for (const l of lista) await window.bela.livros.salvar(l) }, lidos)
    await janela.getByRole('link', { name: 'Configurações', exact: true }).click()
    await janela.getByLabel('Nome do perfil').fill('Leitora Bela')
    await janela.getByLabel('Frase de perfil').fill('Um capítulo por vez.')
    const png = await sharp({ create: { width: 200, height: 200, channels: 3, background: '#23595C' } }).png().toBuffer()
    await janela.getByLabel('Foto do perfil', { exact: true }).setInputFiles({ name: 'foto.png', mimeType: 'image/png', buffer: png })
    await janela.getByLabel('Imagem do topo', { exact: true }).setInputFiles({ name: 'topo.png', mimeType: 'image/png', buffer: png })
    await janela.getByRole('button', { name: 'Salvar perfil', exact: true }).click()
    await expect(janela.getByText('Perfil salvo.', { exact: true })).toBeVisible()
    await janela.getByRole('link', { name: 'Perfil', exact: true }).click()
    await expect(janela.getByRole('heading', { name: 'Leitora Bela', exact: true })).toBeVisible()
    await expect(janela.getByText('Um capítulo por vez.', { exact: true })).toBeVisible()
    await janela.getByRole('button', { name: 'Escolher favoritos', exact: true }).click()
    await expect(janela.getByRole('button', { name: 'Selecionar Brisa', exact: true })).toHaveCount(0)
    for (const nome of ['Aurora', 'Folha', 'Gema', 'Hera']) await janela.getByRole('button', { name: `Selecionar ${nome}`, exact: true }).click()
    await expect(janela.getByRole('button', { name: 'Selecionar Íris', exact: true })).toBeDisabled()
    await janela.getByRole('button', { name: 'Subir favorito 2', exact: true }).click()
    await janela.getByRole('button', { name: 'Salvar seleção', exact: true }).click()
    await expect(janela.getByRole('link', { name: 'Favorito: Folha', exact: true })).toBeVisible()
    // Tirar um favorito pela lista de ordem libera o lugar para outro.
    await janela.getByRole('button', { name: 'Escolher favoritos', exact: true }).click()
    await janela.getByRole('button', { name: 'Remover favorito 3', exact: true }).click()
    await janela.getByRole('button', { name: 'Selecionar Íris', exact: true }).click()
    await janela.getByRole('button', { name: 'Salvar seleção', exact: true }).click()
    await expect(janela.getByRole('link', { name: 'Favorito: Íris', exact: true })).toBeVisible()
    await expect(janela.getByRole('link', { name: 'Favorito: Gema', exact: true })).toHaveCount(0)
    await janela.getByLabel('Página atual de Brisa', { exact: true }).fill('42')
    await janela.getByRole('button', { name: 'Salvar progresso', exact: true }).click()
    await expect(janela.getByText('Página salva para hoje.', { exact: true })).toBeVisible()
    await janela.getByRole('button', { name: 'Subir na fila: Duna', exact: true }).click()
    await expect.poll(async () => (await janela.evaluate(() => window.bela.perfil.painel(new Date().getFullYear()))).fila[0].titulo).toBe('Duna')
    await janela.getByRole('button', { name: 'Definir', exact: true }).click()
    await janela.getByLabel('Livros da meta anual').fill('12')
    await janela.getByRole('button', { name: 'Salvar meta do perfil', exact: true }).click()
    await expect(janela.getByRole('progressbar')).toHaveAttribute('max', '12')
    await janela.reload()
    const painel = await janela.evaluate(() => window.bela.perfil.painel(new Date().getFullYear()))
    expect(painel).toMatchObject({ perfil: { nome: 'Leitora Bela' }, favoritos: [{ titulo: 'Folha' }, { titulo: 'Aurora' }, { titulo: 'Hera' }, { titulo: 'Íris' }], lendo: [{ pagina: 42 }], meta: 12 })
    expect(painel.perfil.foto).toBeTruthy(); expect(painel.perfil.topo).toBeTruthy()
    await expect(janela.locator('.perfil-avatar')).toBeVisible()
    await janela.screenshot({ path: 'test-results/etapa6-perfil.png', fullPage: true, animations: 'disabled' })
    await janela.getByRole('link', { name: 'Estatísticas', exact: true }).click()
    await janela.getByLabel('Meta', { exact: true }).fill('15')
    await janela.getByLabel('Meta', { exact: true }).press('Tab')
    await expect.poll(async () => (await janela.evaluate(() => window.bela.perfil.painel(new Date().getFullYear()))).meta).toBe(15)
    await janela.getByRole('link', { name: 'Perfil', exact: true }).click()
    await expect(janela.getByRole('progressbar')).toHaveAttribute('max', '15')
    await janela.goto(`${janela.url().split('#')[0]}#/retrospectiva/imagem/${new Date().getFullYear()}`)
    await expect(janela.locator('.retro-imagem header')).toContainText('Leitora Bela')
  })

  test('cria lista ordenada, adiciona livros, reordena e preserva livros ao retirar ou excluir', async () => {
    await janela.getByRole('link', { name: 'Listas', exact: true }).click()
    await janela.getByRole('button', { name: 'Nova lista', exact: true }).click()
    await janela.getByLabel('Nome da lista').fill('Próximas aventuras')
    await janela.getByLabel('Tipo da lista').selectOption('ordenada')
    await janela.getByLabel('Descrição da lista').fill('Ordem que escolhi.')
    await janela.getByRole('button', { name: 'Criar lista', exact: true }).click()
    await expect(janela.getByRole('heading', { name: 'Próximas aventuras', exact: true })).toBeVisible()
    await janela.getByRole('button', { name: 'Adicionar livros', exact: true }).click()
    await janela.getByRole('button', { name: 'Selecionar Céu', exact: true }).click()
    await janela.getByRole('button', { name: 'Selecionar Duna', exact: true }).click()
    await janela.getByRole('button', { name: 'Salvar seleção', exact: true }).click()
    await expect(janela.locator('.lista-livro')).toHaveCount(2)
    await janela.getByRole('button', { name: 'Subir Duna', exact: true }).click()
    await expect(janela.locator('.lista-livro h3').first()).toHaveText('Duna')
    await janela.reload()
    await expect(janela.locator('.lista-livro h3').first()).toHaveText('Duna')
    await janela.getByRole('button', { name: 'Editar lista', exact: true }).click()
    await janela.getByLabel('Tipo da lista').selectOption('livre')
    await janela.getByRole('button', { name: 'Salvar lista', exact: true }).click()
    await expect(janela.locator('.lista-livro h3').first()).toHaveText('Céu')
    await janela.screenshot({ path: 'test-results/etapa6-lista.png', fullPage: true, animations: 'disabled' })
    await janela.getByRole('button', { name: 'Retirar Céu da lista', exact: true }).click()
    await expect(janela.locator('.lista-livro')).toHaveCount(1)
    await janela.getByRole('button', { name: 'Excluir lista', exact: true }).click()
    await janela.getByRole('button', { name: 'Confirmar exclusão da lista', exact: true }).click()
    await expect(janela.getByRole('heading', { name: 'Suas listas', exact: true })).toBeVisible()
    expect(await janela.evaluate(async () => (await window.bela.estado()).livros)).toBe(5)
  })

  test('revisa Goodreads, exporta, cria backup completo e restaura após confirmação', async () => {
    await janela.getByRole('link', { name: 'Configurações', exact: true }).click()
    const csv = 'Title,Author,Exclusive Shelf,My Rating,Date Read,My Review\nAurora,Autora,read,1,2020/01/01,Não sobrescrever\nFronteira,Autora,read,4.5,2024/01/10,Boa leitura\n,Autora,read,3,,Erro'
    await janela.getByLabel('Arquivo CSV do Goodreads').setInputFiles({ name: 'goodreads.csv', mimeType: 'text/csv', buffer: Buffer.from(csv) })
    await expect(janela.getByRole('heading', { name: 'Prévia da importação' })).toBeVisible()
    expect(await janela.evaluate(async () => (await window.bela.estado()).livros)).toBe(5)
    await janela.getByRole('button', { name: 'Importar 1 livros novos', exact: true }).click()
    await expect(janela.getByText('1 livros adicionados; 2 registros ignorados.', { exact: true })).toBeVisible()
    expect(await janela.evaluate(async () => (await window.bela.livros.obter(1))?.leituras[0].nota)).toBe(5)
    const exportado = join(raiz, 'livros.csv')
    await app.evaluate(({ dialog }, arquivo) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: arquivo }) }, exportado)
    await janela.getByRole('button', { name: 'Exportar CSV', exact: true }).click()
    await expect(janela.getByText(`CSV salvo: ${exportado}`, { exact: true })).toBeVisible()
    expect(readFileSync(exportado, 'utf8')).toContain('Fronteira')
    const backup = join(raiz, 'biblioteca.bela')
    await app.evaluate(({ dialog }, arquivo) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: arquivo }) }, backup)
    await janela.getByRole('button', { name: 'Criar backup', exact: true }).click()
    await expect(janela.getByText(`Backup salvo: ${backup}`, { exact: true })).toBeVisible()
    expect(existsSync(backup)).toBe(true)
    await janela.evaluate(async (livro) => { await window.bela.livros.salvar(livro); await window.bela.perfil.salvar({ nome: 'Depois do backup', frase: '' }) }, dados('Somente depois'))
    await janela.reload()
    await expect(janela.getByLabel('Nome do perfil')).toHaveValue('Depois do backup')
    await app.evaluate(({ dialog }, arquivo) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [arquivo] }) }, backup)
    await janela.getByRole('button', { name: 'Restaurar backup', exact: true }).click()
    await expect(janela.getByRole('heading', { name: 'Conferir restauração' })).toBeVisible()
    await expect(janela.getByRole('button', { name: 'Confirmar restauração' })).toBeDisabled()
    expect(await janela.evaluate(async () => (await window.bela.estado()).livros)).toBe(7)
    await janela.getByLabel('Conferi e quero substituir a biblioteca por este backup').check()
    await janela.getByRole('button', { name: 'Confirmar restauração' }).click()
    await expect(janela.getByText(/Biblioteca restaurada\. Backup anterior:/)).toBeVisible()
    expect(await janela.evaluate(async () => (await window.bela.estado()).livros)).toBe(6)
    await expect(janela.getByLabel('Nome do perfil')).toHaveValue('Isabela')
    const capa = await janela.evaluate(async () => (await window.bela.livros.obter(1))!.capa)
    expect(capa).toContain('restaurado-')
    await janela.getByRole('button', { name: /^Sem capa/ }).click()
    await expect(janela.locator('.pendencias-livros .livro')).toHaveCount(5)
    await janela.screenshot({ path: 'test-results/etapa6-configuracoes.png', fullPage: true, animations: 'disabled' })
  })
})
