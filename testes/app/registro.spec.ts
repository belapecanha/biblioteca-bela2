import { mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { _electron as electron, expect, test, type ElectronApplication, type Page } from '@playwright/test'
import sharp from 'sharp'

test.describe('etapa 4: registro', () => {
  let pasta: string
  let app: ElectronApplication
  let janela: Page
  let erros: string[]
  test.beforeEach(async () => {
    pasta = mkdtempSync(join(tmpdir(), 'bela-etapa4-'))
    const { ELECTRON_RENDERER_URL: _url, ELECTRON_RUN_AS_NODE: _node, ...ambiente } = process.env
    app = await electron.launch({ args: [resolve('.')], env: { ...ambiente, BELA_PASTA_DADOS: pasta, BELA_ARQUIVO_ENV: join(pasta, '.env') } as Record<string, string> })
    janela = await app.firstWindow()
    erros = []
    janela.on('pageerror', (e) => erros.push(e.message))
    janela.on('console', (e) => { if (e.type() === 'error') erros.push(e.text()) })
    await janela.setViewportSize({ width: 1400, height: 900 })
  })
  test.afterEach(async () => {
    try { expect(erros).toEqual([]) } finally { await app.close(); rmSync(pasta, { recursive: true, force: true, maxRetries: 3 }) }
  })
  test('cadastra com capa, edita dados e datas, registra progresso e releitura independente', async () => {
    await janela.getByRole('link', { name: '+ Registrar' }).click()
    await janela.getByLabel('Título', { exact: true }).fill('Livro de registro')
    await janela.getByLabel('Nome do colaborador 1', { exact: true }).fill('Autora de teste')
    await janela.getByLabel('Número de páginas', { exact: true }).fill('200')
    await janela.getByLabel('Status do livro').selectOption('lido')
    await janela.getByLabel('Precisão da primeira conclusão').selectOption('dia')
    await janela.getByLabel('Data da primeira conclusão').fill('2025-01-15')
    await janela.getByRole('button', { name: 'Dar nota 4,5', exact: true }).click()
    await janela.getByLabel('Resenha da primeira leitura').fill('A primeira impressão.')
    const imagem = await sharp({ create: { width: 180, height: 270, channels: 3, background: '#7E2F3A' } }).png().toBuffer()
    await janela.getByLabel('Escolher capa', { exact: true }).setInputFiles({ name: 'capa.png', mimeType: 'image/png', buffer: imagem })
    await janela.locator('summary', { hasText: 'Gêneros' }).click()
    await janela.getByRole('button', { name: 'Fantasia', exact: true }).click()
    await janela.evaluate(() => window.scrollTo(0, 0))
    await janela.screenshot({ path: 'test-results/etapa4-registrar.png', fullPage: true, animations: 'disabled' })
    await janela.getByRole('button', { name: 'Salvar livro', exact: true }).click()
    await expect(janela.getByRole('heading', { name: 'Livro de registro', exact: true })).toBeVisible()
    await expect(janela.getByText('4,5 de 5. Clique de novo para apagar.')).toBeVisible()
    expect(await janela.locator('.ficha-lado img').evaluate((i: HTMLImageElement) => i.complete && i.naturalWidth > 0)).toBe(true)
    await janela.getByRole('link', { name: 'Diário', exact: true }).click()
    await janela.getByLabel('Mês do diário').selectOption('1')
    await expect(janela.getByRole('link', { name: 'Livro de registro, concluído em 15/1/2025' })).toBeVisible()
    await janela.getByRole('button', { name: 'Mês anterior' }).isDisabled().then((v) => expect(v).toBe(true))
    await janela.getByRole('link', { name: 'Livro de registro, concluído em 15/1/2025' }).click()
    await janela.getByRole('button', { name: 'Registrar releitura', exact: true }).click()
    await janela.getByLabel('Data de início', { exact: true }).fill('2026-02-01')
    await janela.getByRole('form', { name: 'Nova leitura' }).getByRole('button', { name: 'Dar nota 3,5', exact: true }).click()
    await janela.getByLabel('Resenha desta leitura').fill('Na releitura, mudei de ideia.')
    await janela.getByRole('button', { name: 'Salvar leitura', exact: true }).click()
    await expect(janela.getByText('3,5 de 5. Clique de novo para apagar.')).toBeVisible()
    await janela.getByLabel('Data do progresso').fill('2026-02-03')
    await janela.getByLabel('Página alcançada').fill('120')
    await janela.getByRole('button', { name: 'Salvar progresso', exact: true }).click()
    await expect(janela.getByText('Progresso salvo.', { exact: true })).toBeVisible()
    await janela.getByRole('button', { name: 'Editar leitura 2', exact: true }).click()
    await janela.getByLabel('Status da leitura', { exact: true }).selectOption('lido')
    await janela.getByLabel('Data de conclusão', { exact: true }).fill('2026-02-08')
    await janela.getByRole('button', { name: 'Salvar leitura', exact: true }).click()
    await expect(janela.getByRole('button', { name: 'Registrar releitura', exact: true })).toBeEnabled()
    await janela.getByLabel('Trecho da citação').fill('Uma frase para guardar.')
    await janela.getByLabel('Página da citação').fill('42')
    await janela.getByRole('button', { name: 'Guardar citação', exact: true }).click()
    await expect(janela.locator('blockquote')).toContainText('Uma frase para guardar.')
    await janela.getByLabel('Suas anotações sobre o livro').fill('Lembrar do capítulo final.')
    await janela.getByRole('button', { name: 'Salvar notas', exact: true }).click()
    await expect(janela.getByText('Notas salvas.', { exact: true })).toBeVisible()
    await janela.getByRole('button', { name: 'Editar leitura 1', exact: true }).click()
    await janela.getByLabel('Precisão da conclusão').selectOption('ano')
    await janela.getByLabel('Ano da conclusão').fill('2024')
    await janela.getByRole('button', { name: 'Salvar leitura', exact: true }).click()
    const capaAnterior = await janela.evaluate(async () => (await window.bela.livros.obter(1))!.capa)
    await janela.getByRole('link', { name: 'Editar dados e capa' }).click()
    await janela.getByLabel('Título', { exact: true }).fill('Livro de registro revisado')
    await janela.getByLabel('Idioma', { exact: true }).fill('Português')
    const novaImagem = await sharp({ create: { width: 180, height: 270, channels: 3, background: '#23595C' } }).png().toBuffer()
    await janela.getByLabel('Escolher capa', { exact: true }).setInputFiles({ name: 'nova-capa.png', mimeType: 'image/png', buffer: novaImagem })
    await janela.getByRole('button', { name: 'Salvar alterações', exact: true }).click()
    await expect(janela.getByRole('heading', { name: 'Livro de registro revisado', exact: true })).toBeVisible()
    await janela.reload()
    await expect(janela.getByRole('heading', { name: 'Livro de registro revisado', exact: true })).toBeVisible()
    await expect(janela.getByLabel('Suas anotações sobre o livro')).toHaveValue('Lembrar do capítulo final.')
    const livro = await janela.evaluate(async () => window.bela.livros.obter(1))
    expect(livro!.capa).not.toBe(capaAnterior)
    expect(livro).toMatchObject({ idioma: 'Português', leituras: [{ nota: 3.5, resenha: 'Na releitura, mudei de ideia.' }, { nota: 4.5, anoFim: 2024, precisaoFim: 'ano', dataFim: null }], progresso: [{ pagina: 120 }], citacoes: [{ texto: 'Uma frase para guardar.' }] })
    await janela.evaluate(() => window.scrollTo(0, 0))
    await janela.screenshot({ path: 'test-results/etapa4-ficha.png', fullPage: true, animations: 'disabled' })
    await janela.getByRole('link', { name: 'Diário', exact: true }).click()
    await janela.getByLabel('Ano do diário').selectOption('2026')
    await janela.getByLabel('Mês do diário').selectOption('2')
    await expect(janela.getByRole('link', { name: 'Livro de registro revisado, concluído em 8/2/2026' })).toBeVisible()
    await janela.screenshot({ path: 'test-results/etapa4-diario.png', fullPage: true, animations: 'disabled' })
    await janela.getByLabel('Ano do diário').selectOption('2024')
    await expect(janela.getByRole('heading', { name: 'Sem dia exato · 2024' })).toBeVisible()
    await expect(janela.getByRole('region', { name: /Calendário/ }).getByRole('link')).toHaveCount(0)
  })

  test('Google Books exige revisão, avisa duplicados e lê a chave do .env sem exibi-la', async () => {
    await janela.getByRole('link', { name: 'Configurações', exact: true }).click()
    await expect(janela.getByText('Nenhuma chave válida no arquivo .env.', { exact: true })).toBeVisible()
    writeFileSync(join(pasta, '.env'), 'GOOGLE_BOOKS_API_KEY=chave-local-para-teste\n')
    expect(await janela.evaluate(() => window.bela.google.configuracao())).toEqual({ configurada: true, arquivo: expect.any(String) })
    await janela.reload()
    await janela.getByRole('link', { name: 'Configurações', exact: true }).click()
    await expect(janela.getByText('Chave encontrada no arquivo .env.', { exact: true })).toBeVisible()
    await expect(janela.getByText('chave-local-para-teste')).toHaveCount(0)
    // O provedor externo é substituído somente neste processo de teste.
    await app.evaluate(({ ipcMain }) => {
      ipcMain.removeHandler('google:buscar')
      ipcMain.handle('google:buscar', () => [{ googleId: 'teste', titulo: 'Resultado para revisar', autores: ['Autora Google'], editora: 'Editora Google', anoEdicao: 2020, paginas: 180, idioma: 'pt', sinopse: 'Sinopse importada.', isbn10: null, isbn13: '9788535914849', capaUrl: null, fonte: 'google' }])
    })
    async function buscar() {
      await janela.getByRole('link', { name: '+ Registrar', exact: true }).click()
      await janela.getByLabel('Título, autor ou ISBN no Google Books').fill('Resultado')
      await janela.getByRole('button', { name: 'Buscar no Google Books', exact: true }).click()
      await janela.getByRole('button', { name: /Resultado para revisar/ }).click()
      await expect(janela.getByLabel('Título', { exact: true })).toHaveValue('Resultado para revisar')
    }
    await buscar()
    expect(await janela.evaluate(async () => (await window.bela.estado()).livros)).toBe(0)
    await janela.getByRole('button', { name: 'Salvar livro', exact: true }).click()
    await expect(janela.getByRole('heading', { name: 'Resultado para revisar', exact: true })).toBeVisible()
    await buscar()
    await janela.getByRole('button', { name: 'Salvar livro', exact: true }).click()
    await expect(janela.getByRole('heading', { name: 'Este livro pode já estar na biblioteca' })).toBeVisible()
    expect(await janela.evaluate(async () => (await window.bela.estado()).livros)).toBe(1)
    await janela.getByLabel('Conferi e quero salvar esta edição mesmo assim').check()
    await janela.getByRole('button', { name: 'Salvar livro', exact: true }).click()
    await expect(janela.getByRole('heading', { name: 'Resultado para revisar', exact: true })).toBeVisible()
    expect(await janela.evaluate(async () => (await window.bela.estado()).livros)).toBe(2)
    rmSync(join(pasta, '.env'))
    await janela.getByRole('link', { name: 'Configurações', exact: true }).click()
    await expect(janela.getByText('Nenhuma chave válida no arquivo .env.', { exact: true })).toBeVisible()
  })
})
